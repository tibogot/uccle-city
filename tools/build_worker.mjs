// Bundles viewer/tileWorker.js (+ tileData.js, vendor/roads, three's earcut) into
// viewer/tileWorker.bundle.js, which is committed so the viewer still needs no build step.
// Run after changing tileData.js, surfaces.js, heightmap.js, facadeGeom.js, landcover.js, roadData.js or vendor/roads:
//   cd tools/worker && npm install && cd ../.. && node tools/build_worker.mjs
import { build } from "./worker/node_modules/esbuild/lib/main.js";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
await build({
  entryPoints: ["viewer/tileWorker.js"], bundle: true, format: "esm", target: "es2022",
  outfile: "viewer/tileWorker.bundle.js", legalComments: "inline",
  banner: { js: "// GENERATED by tools/build_worker.mjs from viewer/tileWorker.js: do not edit. three.js earcut (MIT) included." },
  nodePaths: ["tools/worker/node_modules"], logLevel: "info",
});
// perfgame round 4: the bundle's own content hash, written into it (the tile cache's key: viewer/tileCache.js codeHash);
// the worker used to fetch its own 670 KB file to hash it at the first tile, behind the boot's downloads (5 s+ on the
// dev server: the cache read missed its deadline and the cache went off)
{
  const f = "viewer/tileWorker.bundle.js";
  const src = readFileSync(f, "utf8").replace(/\r?\nself\.__TILE_CODE_HASH = "[0-9a-f]+";\s*$/, "").replace(/\s*$/, "\n");
  const h = createHash("sha1").update(src).digest("hex").slice(0, 16);
  writeFileSync(f, src + `self.__TILE_CODE_HASH = "${h}";\n`);
}
