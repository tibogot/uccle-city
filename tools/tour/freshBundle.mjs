// The tile-worker bundle built from a checkout's OWN sources, in memory (rule tour-fresh-bundle).
//
// The viewer always loads the committed viewer/tileWorker.bundle.js, and only tools/merge.mjs rebuilds it (after the
// merge, in the main repo). So a branch worktree serves a bundle built from the foundation it started from: every
// tile-side change (parking, lanes, gardens, façades: anything under viewer/tileWorker.js's imports) is NOT in what the
// browser draws. tools/tour/serve.mjs serves this fresh build instead, so a branch's tour shows the branch.
//
//   import { buildBundle } from "./freshBundle.mjs";
//   const { code, hash } = await buildBundle("C:/.../uccle-jobs/lanes5");   // same text + hash stamp as build_worker.mjs
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const BANNER = "// GENERATED by tools/build_worker.mjs from viewer/tileWorker.js: do not edit. three.js earcut (MIT) included.";

export async function buildBundle(root) {
  const mods = path.join(HERE, "tools", "worker", "node_modules");
  const { build } = await import(pathToFileURL(path.join(mods, "esbuild", "lib", "main.js")).href);
  const r = await build({
    entryPoints: [path.join(root, "viewer", "tileWorker.js")], bundle: true, format: "esm", target: "es2022",
    write: false, metafile: true, legalComments: "inline", banner: { js: BANNER }, nodePaths: [mods], absWorkingDir: root, logLevel: "silent",
  });
  const src = r.outputFiles[0].text.replace(/\s*$/, "\n");
  const hash = createHash("sha1").update(src).digest("hex").slice(0, 16);
  const inputs = Object.keys(r.metafile.inputs).map((f) => f.replace(/\\/g, "/")).filter((f) => !f.includes("node_modules"));
  return { code: src + `self.__TILE_CODE_HASH = "${hash}";\n`, hash, inputs };
}

/** the committed bundle's stamped hash in a checkout (null if none) */
export async function committedHash(root) {
  const fs = await import("node:fs");
  const m = /self\.__TILE_CODE_HASH = "([0-9a-f]+)"/.exec(fs.readFileSync(path.join(root, "viewer", "tileWorker.bundle.js"), "utf8"));
  return m ? m[1] : null;
}
